c.setFillColor(colors.HexColor("#6D501D")); c.setFont("Helvetica-Bold",9); c.drawCentredString(425,108,"Patient-level train / validation / test · baseline + hybrid · proxy-label metrics")
c.setFillColor(colors.HexColor("#526A68")); c.setFont("Helvetica",8); c.drawString(42,28,"All records are generated by the included scripts. Scores do not represent clinical event probabilities.")
